@Composable
fun MetricCard(
    title: String,
    value: String,
    icon: ImageVector,
    accentColor: Color,
    modifier: Modifier = Modifier,
    subtitle: String? = null
) {
    Card(
        modifier = modifier.testTag("metric_card_${title.replace(" ", "_")}"),
        shape = RoundedCornerShape(14.dp),
        colors = CardDefaults.cardColors(
            containerColor = MaterialTheme.colorScheme.surface
        ),
        elevation = CardDefaults.cardElevation(defaultElevation = 1.5.dp)
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .padding(14.dp)
        ) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    text = title,
                    style = MaterialTheme.typography.labelMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
                Box(
                    modifier = Modifier
                        .size(32.dp)
                        .background(accentColor.copy(alpha = 0.12f), RoundedCornerShape(8.dp)),
                    contentAlignment = Alignment.Center
                ) {
                    Icon(
                        imageVector = icon,
                        contentDescription = null,
                        tint = accentColor,
                        modifier = Modifier.size(18.dp)
                    )
                }
            }
            Spacer(modifier = Modifier.height(8.dp))
            Text(
                text = value,
                style = MaterialTheme.typography.titleLarge,
                fontWeight = FontWeight.Bold,
                color = MaterialTheme.colorScheme.onSurface
            )
            if (subtitle != null) {
                Spacer(modifier = Modifier.height(2.dp))
                Text(
                    text = subtitle,
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.8f)
                )
            }
        }
    }
}

@Composable
fun StatusBadge(
    status: String,
    modifier: Modifier = Modifier
) {
    val normalized = status.uppercase()
    val bgColor = when (normalized) {
        "PAID" -> StatusSuccess.copy(alpha = 0.12f)
        "PARTIALLY_PAID" -> StatusWarning.copy(alpha = 0.15f)
        "UNPAID" -> StatusDanger.copy(alpha = 0.12f)
        "LOW_STOCK" -> StatusWarning.copy(alpha = 0.15f)
        "OUT_OF_STOCK" -> StatusDanger.copy(alpha = 0.12f)
        else -> Color.Gray.copy(alpha = 0.12f)
    }
    val textColor = when (normalized) {
        "PAID" -> StatusSuccess
        "PARTIALLY_PAID" -> StatusWarning
        "UNPAID" -> StatusDanger
        "LOW_STOCK" -> StatusWarning
        "OUT_OF_STOCK" -> StatusDanger
        else -> Color.DarkGray
    }
    val label = when (normalized) {
        "PAID" -> stringResource(R.string.status_paid)
        "PARTIALLY_PAID" -> stringResource(R.string.status_partially_paid)
        "UNPAID" -> stringResource(R.string.status_unpaid)
        "LOW_STOCK" -> stringResource(R.string.product_low_stock)
        "OUT_OF_STOCK" -> stringResource(R.string.product_out_of_stock)
        else -> normalized
    }

    Box(
        modifier = modifier
            .background(bgColor, RoundedCornerShape(6.dp))
            .padding(horizontal = 8.dp, vertical = 3.dp),
        contentAlignment = Alignment.Center
    ) {
        Text(
            text = label,
            color = textColor,
            fontSize = 11.sp,
            fontWeight = FontWeight.Bold
        )
    }
}

@Composable
